import 'package:iroyal/app/modules/tracking_document/data/models/company_model.dart';
import 'package:iroyal/app/modules/tracking_document/data/models/content_model.dart';
import 'package:iroyal/app/modules/tracking_document/domain/entities/tracking_document.dart';

class TrackingDocumentModel extends TrackingDocument {
  const TrackingDocumentModel({
    required super.id,
    required super.content,
    required super.additionalCriteria,
    required super.reason,
    required super.reasonDescription,
    required super.status,
    required super.approvedBy,
    required super.complete,
    required super.createdAt,
    required super.updatedAt,
    required super.userId,
    required super.aasmState,
    required super.submissionId,
    required super.serialNumber,
    required super.title,
    required super.priority,
    required super.recipientId,
    required super.isCompleted,
    required super.laborQuantity,
    required super.replacedEmployeeId,
    required super.company,
    required super.department,
    required super.location,
    required super.position,
    required super.employmentStatus,
    required super.section,
  });

  factory TrackingDocumentModel.fromJson(Map<String, dynamic> json) =>
      TrackingDocumentModel(
        id: json["id"],
        content: ContentModel.fromJson(json["content"]),
        additionalCriteria: json["additional_criteria"],
        reason: json["reason"],
        reasonDescription: ContentModel.fromJson(json["reason_description"]),
        status: json["status"],
        approvedBy: json["approved_by"],
        complete: json["complete"],
        createdAt: DateTime.parse(json["created_at"]),
        updatedAt: DateTime.parse(json["updated_at"]),
        userId: json["user_id"],
        aasmState: json["aasm_state"],
        submissionId: json["submission_id"],
        serialNumber: json["serial_number"],
        title: json["title"],
        priority: json["priority"],
        recipientId: json["recipient_id"],
        isCompleted: json["is_completed"],
        laborQuantity: json["labor_quantity"],
        replacedEmployeeId: json["replaced_employee_id"],
        company: CompanyModel.fromJson(json["company"]),
        department: CompanyModel.fromJson(json["department"]),
        location: CompanyModel.fromJson(json["location"]),
        position: CompanyModel.fromJson(json["position"]),
        employmentStatus: CompanyModel.fromJson(json["employment_status"]),
        section: CompanyModel.fromJson(json["section"]),
      );

  Map<String, dynamic> toJson() => {
        "id": id,
        "content": content.toJson(),
        "additional_criteria": additionalCriteria,
        "reason": reason,
        "reason_description": reasonDescription.toJson(),
        "status": status,
        "approved_by": approvedBy,
        "complete": complete,
        "created_at": createdAt.toIso8601String(),
        "updated_at": updatedAt.toIso8601String(),
        "user_id": userId,
        "aasm_state": aasmState,
        "submission_id": submissionId,
        "serial_number": serialNumber,
        "title": title,
        "priority": priority,
        "recipient_id": recipientId,
        "is_completed": isCompleted,
        "labor_quantity": laborQuantity,
        "replaced_employee_id": replacedEmployeeId,
        "company": company.toJson(),
        "department": department.toJson(),
        "location": location.toJson(),
        "position": position.toJson(),
        "employment_status": employmentStatus.toJson(),
        "section": section.toJson(),
      };
}
